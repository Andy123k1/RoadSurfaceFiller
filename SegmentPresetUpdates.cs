using System;
using System.Collections.Generic;
using System.Diagnostics;
using Colossal.Serialization.Entities;
using Unity.Collections;
using Unity.Entities;

namespace SurfaceNetworkFilter
{
    // A separate optional component keeps the existing segment save format
    // readable. An empty ID marks an intentional independent customization.
    public struct SavedSegmentPresetLink : IComponentData, ISerializable
    {
        public FixedString64Bytes PresetId;
        public void Serialize<TWriter>(TWriter writer) where TWriter : IWriter
        { writer.Write(PresetId.ToString()); }
        public void Deserialize<TReader>(TReader reader) where TReader : IReader
        { reader.Read(out string id); PresetId = new FixedString64Bytes(id); }
    }

    internal static partial class RuntimeState
    {
        internal static int SegmentPresetRevision;
        internal static readonly List<SegmentUpgradePreset> PreviousSegmentPresets = new List<SegmentUpgradePreset>();

        internal static void NotifySegmentPresetsChanged(SegmentUpgradePreset previous = null)
        {
            if (previous != null) PreviousSegmentPresets.Add(previous);
            SegmentPresetRevision++;
        }
    }

    internal sealed partial class SurfaceNetworkFilterSystem
    {
        private readonly Dictionary<string, SegmentUpgradePreset> m_PresetDefinitions = new Dictionary<string, SegmentUpgradePreset>();
        private readonly List<SegmentUpgradePreset> m_LegacyPresetCandidates = new List<SegmentUpgradePreset>();
        private readonly List<Entity> m_PresetUpdateRecords = new List<Entity>();
        private int m_PresetUpdateCursor;
        private readonly HashSet<Entity> m_QueuedPresetRecords = new HashSet<Entity>();
        private readonly HashSet<string> m_FailedPresetUpdates = new HashSet<string>();
        private bool m_PresetLinksInitialized;
        private int m_LastPresetRevision;

        private void ResetSegmentPresetUpdates()
        {
            m_PresetDefinitions.Clear(); m_LegacyPresetCandidates.Clear();
            m_PresetUpdateRecords.Clear(); m_QueuedPresetRecords.Clear(); m_FailedPresetUpdates.Clear();
            m_PresetUpdateCursor = 0;
            m_PresetLinksInitialized = false; m_LastPresetRevision = -1;
            RuntimeState.PreviousSegmentPresets.Clear();
        }

        private string SegmentPresetId(Entity record) => EntityManager.HasComponent<SavedSegmentPresetLink>(record)
            ? EntityManager.GetComponentData<SavedSegmentPresetLink>(record).PresetId.ToString() : null;

        private string LegacySegmentPresetId(Entity record, SavedSegmentSurfaceRule saved)
        {
            string id = null;
            foreach (SegmentUpgradePreset candidate in m_LegacyPresetCandidates)
            {
                if (!m_PresetDefinitions.ContainsKey(candidate.Rule.Id) || !SegmentMatchesPreset(record, saved, candidate)) continue;
                if (id != null && id != candidate.Rule.Id) return ""; // Ambiguous: keep this road independent.
                id = candidate.Rule.Id;
            }
            return id;
        }

        private string CaptureSegmentPresetId(Entity record) => SegmentPresetId(record) ??
            LegacySegmentPresetId(record, EntityManager.GetComponentData<SavedSegmentSurfaceRule>(record));

        private void SetSegmentPresetLink(Entity record, string id)
        {
            if (id == null) return; // Preserve unclassified legacy records when cloning.
            // IDs generated by this mod are 32-character GUIDs. A malformed
            // imported ID must not prevent a road's actual finish being saved.
            if (System.Text.Encoding.UTF8.GetByteCount(id) > 60) id = "";
            SavedSegmentPresetLink link = new SavedSegmentPresetLink { PresetId = new FixedString64Bytes(id) };
            if (EntityManager.HasComponent<SavedSegmentPresetLink>(record)) EntityManager.SetComponentData(record, link);
            else EntityManager.AddComponentData(record, link);
        }

        private bool SegmentMatchesPreset(Entity record, SavedSegmentSurfaceRule saved, SegmentUpgradePreset preset)
        {
            SurfaceRule rule = preset.Rule;
            if (saved.Name.ToString() != rule.Name || saved.Enabled != rule.Enabled ||
                saved.FillBusShoulders != preset.FillBusShoulders ||
                saved.BikeMode != (rule.SeparateBikeLanes.HasValue ? rule.SeparateBikeLanes.Value ? 2 : 1 : 0) ||
                saved.BusMode != (rule.SeparateBusLanes.HasValue ? rule.SeparateBusLanes.Value ? 2 : 1 : 0)) return false;
            DynamicBuffer<SavedSegmentSurfaceTarget> targets = EntityManager.GetBuffer<SavedSegmentSurfaceTarget>(record, true);
            if (targets.Length != rule.Assignments.Count) return false;
            foreach (SavedSegmentSurfaceTarget target in targets)
            {
                SurfaceAssignment assignment = rule.Assignments.Find(item => item != null && item.Target == target.Target);
                if (assignment == null || (assignment.Surface ?? "") != target.SurfaceName.ToString()) return false;
            }
            return true;
        }

        private void QueueSegmentPresetRefresh(Entity record)
        {
            if (!EntityManager.Exists(record) || !EntityManager.HasComponent<SavedSegmentSurfaceRule>(record)) return;
            if (m_PresetLinksInitialized)
            {
                string id = SegmentPresetId(record);
                if (id != null && (id.Length == 0 || !m_PresetDefinitions.TryGetValue(id, out SegmentUpgradePreset preset) ||
                    !preset.UpdateExistingSegments || SegmentMatchesPreset(record,
                        EntityManager.GetComponentData<SavedSegmentSurfaceRule>(record), preset))) return;
            }
            if (m_QueuedPresetRecords.Add(record)) m_PresetUpdateRecords.Add(record);
        }

        private void UpdateSegmentPresetLinks(Setting setting)
        {
            if (!m_PresetLinksInitialized || m_LastPresetRevision != RuntimeState.SegmentPresetRevision)
            {
                m_PresetDefinitions.Clear();
                foreach (SegmentUpgradePreset preset in setting.GetSegmentPresets())
                    if (!string.IsNullOrEmpty(preset.Rule.Id)) m_PresetDefinitions[preset.Rule.Id] = preset;
                m_LegacyPresetCandidates.AddRange(RuntimeState.PreviousSegmentPresets);
                m_LegacyPresetCandidates.AddRange(m_PresetDefinitions.Values);
                RuntimeState.PreviousSegmentPresets.Clear(); m_FailedPresetUpdates.Clear();
                m_PresetLinksInitialized = true; m_LastPresetRevision = RuntimeState.SegmentPresetRevision;
                foreach (Entity record in m_SegmentRuleRecords.Values) QueueSegmentPresetRefresh(record);
                if (m_PresetUpdateRecords.Count == 0)
                { m_LegacyPresetCandidates.Clear(); m_LegacyPresetCandidates.AddRange(m_PresetDefinitions.Values); }
            }

            if (m_PresetUpdateRecords.Count == 0) return;

            // Existing surface reconciliation keeps the old overlays until
            // replacements are ready. Bound metadata updates too, so a large
            // preset edit does not enqueue all geometry work in one frame.
            Stopwatch timer = Stopwatch.StartNew();
            int processed = 0;
            while (m_PresetUpdateCursor < m_PresetUpdateRecords.Count && processed < 24 && (processed == 0 || timer.Elapsed.TotalMilliseconds < 2))
            {
                Entity record = m_PresetUpdateRecords[m_PresetUpdateCursor++]; m_QueuedPresetRecords.Remove(record); processed++;
                if (!EntityManager.Exists(record) || !EntityManager.HasComponent<SavedSegmentSurfaceRule>(record)) continue;
                SavedSegmentSurfaceRule saved = EntityManager.GetComponentData<SavedSegmentSurfaceRule>(record);
                string id = SegmentPresetId(record);
                if (id == null)
                {
                    // Old saves did not record a preset ID. Adopt only one
                    // exact match, including its name, targets and lane modes.
                    id = LegacySegmentPresetId(record, saved);
                    if (id == null) continue;
                    SetSegmentPresetLink(record, id);
                }
                if (string.IsNullOrEmpty(id) || !m_PresetDefinitions.TryGetValue(id, out SegmentUpgradePreset preset) ||
                    !preset.UpdateExistingSegments || !IsRoadEdge(saved.Edge) || SegmentMatchesPreset(record, saved, preset)) continue;
                try
                {
                    SaveSegmentRule(saved.Edge, new SegmentRuleDraft { Rule = preset.Rule,
                        FillBusShoulders = preset.FillBusShoulders, PresetId = id });
                    QueueRoadStyleRebuild(saved.Edge);
                }
                catch (ArgumentException exception)
                {
                    // Keep the saved finish if a required asset is missing.
                    // Catalog refresh or saving the preset queues another try.
                    if (m_FailedPresetUpdates.Add(id)) Mod.Log.Warn("Could not update roads using preset '" + preset.Rule.Name + "': " + exception.Message);
                }
            }
            if (m_PresetUpdateCursor >= m_PresetUpdateRecords.Count)
            {
                m_PresetUpdateRecords.Clear(); m_PresetUpdateCursor = 0;
                m_LegacyPresetCandidates.Clear(); m_LegacyPresetCandidates.AddRange(m_PresetDefinitions.Values);
            }
        }
    }
}
